package com.java.JavaRegex.UserRegistration;

public class User {
    String firstName;
    String lastName;
    String email;
    String mobile;
    String password;

    public User(String firstName, String lastName,
                String email, String mobile, String password) {
        this.firstName = firstName;
        this.lastName = lastName;
        this.email = email;
        this.mobile = mobile;
        this.password = password;
    }
}
